# Persistence helpers
# ============================================================

def _repository_gate_limits(repository_url: str) -> dict | None:
    """Load custom quality gate thresholds for a repository, if any."""
    db = SessionLocal()
    try:
        from app.db_models.repository import Repository
        from app.db_models.quality_gate_config import QualityGateConfig
        repo = db.query(Repository).filter(
            Repository.github_url == repository_url
        ).first()
        if not repo:
            return None
        config = db.query(QualityGateConfig).filter(
            QualityGateConfig.repository_id == repo.id
        ).first()
        if not config:
            return None
        return {
            "critical_limit": config.critical_limit,
            "security_limit": config.security_limit,
            "min_health": config.min_health,
        }
    finally:
        db.close()


def _post_status_check(
    client: GitHubClient,
    owner: str,
    repo_name: str,
    head_sha: str | None,
    pr_url: str | None,
    gate,
) -> bool:
    """
    Post the quality gate verdict as a GitHub commit status check on the
    PR's head commit. Returns True when the status was posted.

    Skips silently when disabled, no token, or no head SHA is available.
    Never raises — a status-check failure must not fail the analysis.
    """
    if not settings.PR_POST_STATUS_CHECK:
        return False
    if not (client.token and head_sha):
        return False
    try:
        client.create_commit_status(
            owner,
            repo_name,
            head_sha,
            state="success" if gate.passed else "failure",
            context=settings.QUALITY_GATE_CONTEXT,
            description=status_check_description(gate),
            target_url=pr_url,
        )
        print(f"[OK] Posted commit status check ({gate.result}) on {head_sha[:8]}")
        return True
    except GitHubError as error:
        logger.warning("Failed to post status check for %s/%s %s: %s",
                       owner, repo_name, head_sha[:8], error)
        return False


def _persist_results(
    *,
    owner: str,
    repo_name: str,
    repository_url: str,
    pull_number: int,
    pr_title: str | None,
    pr_url: str | None,
    base_sha: str | None,
    head_sha: str | None,
    findings: list[ScanFinding],
    gate=None,
) -> int:
    """Create the PrAnalysis row and its findings. Returns the row id."""
    db = SessionLocal()
    try:
        repo = find_or_create_repository(
            db, github_url=repository_url, owner=owner, name=repo_name
        )
        record = PrAnalysis(
            repository_id=repo.id,
            pull_number=pull_number,
            pr_title=pr_title,
            pr_url=pr_url,
            base_sha=base_sha,
            head_sha=head_sha,
            status="COMPLETED",
            findings_count=len(findings),
            completed_at=datetime.now(timezone.utc),
            gate_result=getattr(gate, "result", None),
            gate_reasons=("\n".join(gate.reasons) if gate and gate.reasons else None),
        )
        db.add(record)
        db.flush()

        for finding in findings:
            db.add(PrFinding(
                pr_analysis_id=record.id,
                category=finding.category,
                severity=finding.severity,
                priority=finding.priority,
                file_path=finding.file_path,
                line_start=finding.line_start,
                code_snippet=finding.code_snippet,
                message=finding.message,
                recommendation=finding.recommendation,
                source="rule",
                confidence=finding.confidence,
            ))

        db.commit()
        return record.id
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def _mark_comment_posted(pr_analysis_id: int) -> None:
    """Mark the PR analysis as having its comment posted."""
    db = SessionLocal()
    try:
        record = db.get(PrAnalysis, pr_analysis_id)
        if record:
            record.comment_posted = True
            db.commit()
    except Exception:
        db.rollback()
    finally:
        db.close()


def _mark_status_check_posted(pr_analysis_id: int) -> None:
    """Mark the PR analysis as having its status check posted."""
    db = SessionLocal()
    try:
        record = db.get(PrAnalysis, pr_analysis_id)
        if record:
            record.status_check_posted = True
            db.commit()
    except Exception:
        db.rollback()
    finally:
        db.close()