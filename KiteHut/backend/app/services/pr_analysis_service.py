"""
Pull Request Analysis Service (Phase 9).

Flow:
    1. Fetch the pull request and its changed files from GitHub
    2. Scan the *added* lines with deterministic rules (no clone needed)
    3. Persist a PrAnalysis row + PrFinding rows
    4. Optionally post a summary comment back to the PR

Returns a dict with pr_analysis_id / findings_count / error, mirroring
analysis_service.run_analysis so the async job layer can treat both the
same way.
"""

